SIZE_RE = re.compile(r"(\d{2,3})")


def normalize_size(raw):
    """'48 (M)' -> '48'; 'XL' -> '' (для <Size> нужен числовой размер)."""
    if not raw:
        return ""
    m = SIZE_RE.search(str(raw))
    return m.group(1) if m else ""


def _norm(value):
    return str(value or "").strip().lower().replace("ё", "е")


def pick_goods_type(category, subcategory, attrs):
    """Определяет <GoodsType> по подкатегории, предмету одежды и категории."""
    avito_cat = CATEGORY_MAP.get(category, DEFAULT_CATEGORY)
    allowed = ALLOWED_GOODS_TYPES.get(avito_cat, set())

    sub = (subcategory or "").strip()
    if sub and sub in allowed:
        return sub

    # ищем по «Предмет одежды» / «Тип одежды» / названию
    hints = []
    for key in ("Предмет одежды", "Тип одежды", "Тип"):
        v = attrs.get(key)
        if v:
            hints.append(str(v))
    hints.append(sub)
    for hint in hints:
        h = _norm(hint)
        if not h:
            continue
        for word, goods in ITEM_TO_GOODS_TYPE.items():
            if word in h and goods in allowed:
                return goods
    if sub and sub in ITEM_TO_GOODS_TYPE:
        return ITEM_TO_GOODS_TYPE[sub]

    return DEFAULT_GOODS_TYPE.get(avito_cat, "Прочее")


def build(item):
    """Возвращает готовые значения для XML Автозагрузки Avito."""
    attrs = item.get("attrs") or {}
    if isinstance(attrs, str):
        import json
        try:
            attrs = json.loads(attrs)
        except Exception:
            attrs = {}
    if not isinstance(attrs, dict):
        attrs = {}

    category = (item.get("category") or "").strip()
    avito_cat = CATEGORY_MAP.get(category, DEFAULT_CATEGORY)

    condition_raw = (item.get("condition") or "").strip()
    condition = CONDITION_MAP.get(_norm(condition_raw), DEFAULT_CONDITION)

    size_raw = (item.get("size") or "").strip()
    if _norm(size_raw) in ("не указан", ""):
        size_raw = ""
    size = normalize_size(size_raw or attrs.get("Размер", ""))

    color = str(attrs.get("Цвет") or "").strip()
    material = str(attrs.get("Материал основной части") or attrs.get("Состав/материал")
                   or attrs.get("Материал") or attrs.get("Материал верха") or "").strip()
    season_raw = str(attrs.get("Сезон") or "").strip()
    season = SEASON_MAP.get(_norm(season_raw), season_raw)

    extra = {}
    for k, v in attrs.items():
        key = _norm(k)
        if not v or key in SKIP_ATTR_KEYS:
            continue
        name = EXTRA_ATTR_NAMES.get(key, k)
        extra[name] = str(v).strip()

    return {
        "category": avito_cat,
        "goods_type": pick_goods_type(category, item.get("subcategory"), attrs),
        "condition": condition,
        "size": size,
        "size_raw": size_raw,
        "color": color,
        "material": material,
        "season": season,
        "extra_attrs": extra,
        "brand": (item.get("brand") or "").strip() or "Неизвестный бренд",
    }
