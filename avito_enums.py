def normalize_size(raw):
    """Приводит размер к значению справочника Авито: «50 (L)», «One size», «Без размера»."""
    s = (raw or "").strip()
    if not s:
        return ""
    low = s.lower().replace("ё", "е")
    for enum in SIZES:                      # точное совпадение со справочником
        if low == enum.lower().replace("ё", "е"):
            return enum
    import re
    num = re.search(r"\b(\d{2,3})\b", s)
    if num:
        n = int(num.group(1))
        if n in _SIZE_BY_NUMBER:
            return _SIZE_BY_NUMBER[n]
        near = min(_SIZE_BY_NUMBER, key=lambda k: abs(k - n))
        return _SIZE_BY_NUMBER[near]
    letters = re.findall(r"[a-z]+", low)
    for token in letters:
        if token in _SIZE_BY_LETTER:
            return _SIZE_BY_NUMBER[_SIZE_BY_LETTER[token]]
    if "one size" in low or "onesize" in low or "безразмер" in low:
        return "One size"
    return ""


def normalize_color(raw):
    """Приводит цвет к справочнику Авито; неизвестное значение — «Разноцветный»."""
    s = (raw or "").strip().lower().replace("ё", "е")
    if not s:
        return ""
    synonyms = {
        "черный": "Чёрный", "чёрный": "Чёрный", "белый": "Белый", "серый": "Серый",
        "синий": "Синий", "голубой": "Голубой", "красный": "Красный",
        "бордовый": "Бордовый", "бордо": "Бордовый", "зеленый": "Зелёный",
        "желтый": "Жёлтый", "коричневый": "Коричневый", "бежевый": "Бежевый",
        "розовый": "Розовый", "фиолетовый": "Фиолетовый", "оранжевый": "Оранжевый",
        "золотой": "Золотой", "серебряный": "Серебряный", "разноцветный": "Разноцветный",
        "хаки": "Зелёный", "молочный": "Белый", "темно-синий": "Синий",
    }
    if s in synonyms:
        return synonyms[s]
    for enum in COLORS:
        if s == enum.lower().replace("ё", "е"):
            return enum
        if enum.lower().replace("ё", "е") in s:
            return enum
    return "Разноцветный"


def apparel_for(subcategory):
    """Возвращает (Apparel, ApparelType, подтверждено_шаблоном)."""
    sub = (subcategory or "").strip()
    if sub in APPAREL_BY_SUBCATEGORY:
        a, at = APPAREL_BY_SUBCATEGORY[sub]
        return a, at, True
    guess = APPAREL_GUESS.get(sub, "")
    return (guess or "Прочая одежда"), (sub if guess else ""), False
